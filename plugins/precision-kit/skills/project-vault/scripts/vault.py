# ------------------------------------------------------------------ helpers
def load(name: str, skill: str):
    for cand in (HERE / name, SKILLS / skill / "scripts" / name):
        if cand.exists():
            spec = importlib.util.spec_from_file_location(name[:-3], cand)
            mod = importlib.util.module_from_spec(spec)
            sys.modules[name[:-3]] = mod
            spec.loader.exec_module(mod)
            return mod
    return None


def git_files(repo: Path) -> list[str]:
    out = subprocess.run(["git", "ls-files", "-co", "--exclude-standard", "-z"], cwd=repo, capture_output=True)
    if out.returncode == 0:
        files = [f for f in out.stdout.decode("utf-8", errors="replace").split("\0") if f]
    else:
        files = [str(p.relative_to(repo)).replace("\\", "/") for p in repo.rglob("*") if p.is_file()]
    return sorted(f for f in files if not set(f.split("/")[:-1]) & SKIP_PARTS and (repo / f).is_file())


def read(repo: Path, rel: str) -> str:
    try:
        p = repo / rel
        return "" if p.stat().st_size > 1_000_000 else p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def claude_md(repo: Path) -> Path:
    """Root CLAUDE.md, or .claude/CLAUDE.md when that is the one the project uses."""
    root, dotted = repo / "CLAUDE.md", repo / ".claude" / "CLAUDE.md"
    return dotted if dotted.exists() and not root.exists() else root


def find_dir(repo: Path, wanted: str | None) -> Path:
    if wanted:
        return repo / wanted
    for cand in ("docs/vault", "vault", ".vault"):
        if (repo / cand).is_dir():
            return repo / cand
    claude = read(repo, str(claude_md(repo).relative_to(repo)))
    m = re.search(r"\]\(([^)]+)/PLAN\.md\)", claude)
    return repo / m.group(1) if m else repo / "docs" / "vault"


def md_table(header: list[str], rows: list[list[str]], limit: int = 200) -> str:
    if not rows:
        return ""
    esc = lambda c: str(c).replace("|", "\\|").replace("\n", " ")
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows[:limit]]
    if len(rows) > limit:
        out.append(f"| ... {len(rows) - limit} more | " + " | ".join("" for _ in header[1:]) + " |")
    return "\n".join(out)


