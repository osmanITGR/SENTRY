def auto_stack(repo: Path, files: list[str]) -> str:
    det = load("detect_stack.py", "codebase-recon")
    fr = load("freshness_report.py", "live-modernize")
    projects = det.detect(repo)["projects"] if det else []
    if not projects:
        return "No buildable project detected yet."
    parts = []
    pins = []
    for name, label in ((".nvmrc", "Node"), (".node-version", "Node"), (".python-version", "Python"),
                        (".tool-versions", "asdf/mise"), ("rust-toolchain.toml", "Rust"), ("global.json", ".NET SDK"),
                        (".fvmrc", "Flutter (FVM)")):
        for f in files:
            if f == name or f.endswith("/" + name):
                pins.append([label, f, read(repo, f).strip().splitlines()[0][:60] if read(repo, f).strip() else ""])
    for f in files:
        if f.endswith("go.mod"):
            m = re.search(r"^go\s+(\S+)", read(repo, f), re.M)
            if m:
                pins.append(["Go", f, m.group(1)])
        if f.endswith("package.json") and "node_modules" not in f:
            try:
                pkg = json.loads(read(repo, f) or "{}")
            except json.JSONDecodeError:
                pkg = {}
            if (pkg.get("engines") or {}).get("node"):
                pins.append(["Node (engines)", f, pkg["engines"]["node"]])
            if pkg.get("packageManager"):
                pins.append(["Package manager", f, pkg["packageManager"]])
        if f.endswith("pubspec.yaml"):
            m = re.search(r"^environment:\s*\n((?:\s+.+\n?)+)", read(repo, f), re.M)
            if m:
                pins.append(["Dart/Flutter SDK", f, " ".join(l.strip() for l in m.group(1).splitlines())[:60]])
        if f.endswith("gradle-wrapper.properties"):
            m = re.search(r"gradle-([\d.]+)-", read(repo, f))
            if m:
                pins.append(["Gradle", f, m.group(1)])
    rows = [[p["root"], p["stack"], p["package_manager"], ", ".join(p.get("frameworks", [])) or "-"] for p in projects]
    parts.append("### Projects\n" + md_table(["Root", "Stack", "Package manager", "Frameworks"], rows))
    if pins:
        parts.append("### Pinned runtimes and tools\n" + md_table(["What", "File", "Version"], sorted(pins)))
    cmds = [[p["root"], k, f"`{v}`"] for p in projects for k, v in p["commands"].items()]
    parts.append("### Commands\n" + md_table(["Root", "Check", "Command"], cmds))
    if fr:
        deps = []
        for collect in fr.COLLECTORS.values():
            try:
                deps += collect(repo)
            except Exception:  # a broken manifest must not stop the vault
                continue
        rows = sorted({(d.manifest, d.ecosystem, d.name, d.current + ("" if d.exact else " (declared)")) for d in deps})
        if rows:
            parts.append(f"### Direct dependencies ({len(rows)})\n" + md_table(["Manifest", "Ecosystem", "Package", "Version"],
                                                                                [list(r) for r in rows], 300))
    return "\n\n".join(parts)


SQL_TABLE = re.compile(r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[`\"\[]?([\w.]+)[`\"\]]?\s*\((.*?)\)\s*;?",
                       re.I | re.S)


def sql_columns(body: str) -> str:
    cols = []
    for part in re.split(r",(?![^()]*\))", body):
        m = re.match(r"\s*[`\"\[]?(\w+)[`\"\]]?\s+([A-Za-z]+(?:\s*\([^)]*\))?)", part)
        if m and m.group(1).upper() not in ("PRIMARY", "FOREIGN", "UNIQUE", "CONSTRAINT", "CHECK", "KEY", "INDEX"):
            cols.append(f"{m.group(1)} {m.group(2).lower()}")
    return ", ".join(cols)


def auto_schema(repo: Path, files: list[str]) -> str:
    rows: list[list[str]] = []
    sources = set()
    for f in files:
        ext = Path(f).suffix
        if ext not in (".sql", ".prisma", ".py", ".ts", ".js", ".kt", ".java", ".dart", ".cs", ".go", ".rb", ".php"):
            continue
        text = read(repo, f)
        if not text:
            continue
        line = lambda pos: text[:pos].count("\n") + 1
        if ext in (".sql",) or "CREATE TABLE" in text.upper():
            for m in SQL_TABLE.finditer(text):
                rows.append([m.group(1), sql_columns(m.group(2))[:160], f"{f}:{line(m.start())}"])
                sources.add("SQL")
        if ext == ".prisma":
            for m in re.finditer(r"^model\s+(\w+)\s*\{(.*?)^\}", text, re.M | re.S):
                cols = [l.split()[0] + " " + l.split()[1] for l in m.group(2).splitlines()
                        if len(l.split()) >= 2 and not l.strip().startswith(("//", "@@"))]
                rows.append([m.group(1), ", ".join(cols)[:160], f"{f}:{line(m.start())}"])
                sources.add("Prisma")
        if ext == ".py":
            for m in re.finditer(r"^class\s+(\w+)\((?:[\w.]*models\.Model|[\w.]*Base|db\.Model|SQLModel)[^)]*\):\n((?:[ \t]+.*\n|\n)*)",
                                 text, re.M):
                body = m.group(2)
                if "models.Model" in m.group(0) or "__tablename__" in body or "Column(" in body or "Field(" in body \
                        or "mapped_column" in body:
                    cols = re.findall(r"^\s+(\w+)\s*(?::\s*[\w\[\], |.]+)?\s*=\s*(?:models\.(\w+)|(?:db\.)?Column\(\s*([\w.]+)|"
                                      r"mapped_column\(\s*([\w.]*)|Field\()", body, re.M)
                    desc = ", ".join(c[0] + (" " + (c[1] or c[2] or c[3]).split(".")[-1].lower() if (c[1] or c[2] or c[3]) else "")
                                     for c in cols if c[0] not in ("Meta", "objects"))
                    table = re.search(r"__tablename__\s*=\s*['\"](\w+)", body)
                    rows.append([table.group(1) if table else m.group(1), desc[:160], f"{f}:{line(m.start())}"])
                    sources.add("Python ORM")
        if ext in (".ts", ".js", ".kt", ".java", ".cs"):
            for m in re.finditer(r"@Entity(?:\([^)]*\))?\s*(?:export\s+)?(?:data\s+)?(?:public\s+)?class\s+(\w+)", text):
                rows.append([m.group(1), "", f"{f}:{line(m.start())}"])
                sources.add("@Entity")
            for m in re.finditer(r"(?:mongoose\.)?model\(\s*['\"](\w+)['\"]\s*,\s*(\w+)", text):
                rows.append([m.group(1), f"mongoose schema {m.group(2)}", f"{f}:{line(m.start())}"])
                sources.add("Mongoose")
            for m in re.finditer(r"DbSet<(\w+)>\s+(\w+)", text):
                rows.append([m.group(2), f"entity {m.group(1)}", f"{f}:{line(m.start())}"])
                sources.add("EF Core")
        if ext == ".dart":
            for m in re.finditer(r"class\s+(\w+)\s+extends\s+Table\b", text):
                rows.append([m.group(1), "drift table", f"{f}:{line(m.start())}"])
                sources.add("drift")
            for m in re.finditer(r"@HiveType\(typeId:\s*(\d+)\)\s*class\s+(\w+)", text):
                rows.append([m.group(2), f"Hive box type {m.group(1)}", f"{f}:{line(m.start())}"])
                sources.add("Hive")
        if ext == ".go":
            for m in re.finditer(r"type\s+(\w+)\s+struct\s*\{([^}]*gorm:[^}]*)\}", text):
                rows.append([m.group(1), "gorm model", f"{f}:{line(m.start())}"])
                sources.add("GORM")
    migrations = sorted({str(Path(f).parent) for f in files if re.search(r"(^|/)(migrations?|alembic/versions|db/migrate)/", f)})
    seen, uniq = set(), []
    for r in rows:
        if (r[0], r[2]) not in seen:
            seen.add((r[0], r[2]))
            uniq.append(r)
    out = []
    if uniq:
        out.append(f"### Entities ({len(uniq)}; sources: {', '.join(sorted(sources))})\n"
                   + md_table(["Entity/table", "Columns/fields", "Defined at"], sorted(uniq)))
    if migrations:
        out.append("### Migration folders\n" + "\n".join(f"- `{m}`" for m in migrations[:20]))
    return "\n\n".join(out) or "No database schema detected in code."


def auto_tokens(repo: Path, files: list[str]) -> str:
    tokens: list[list[str]] = []
    for f in files:
        ext = Path(f).suffix
        text = read(repo, f) if ext in (".css", ".scss", ".sass", ".less", ".xml", ".dart", ".kt", ".js", ".ts", ".json",
                                        ".mjs", ".cjs") else ""
        if not text:
            continue
        if ext in (".css", ".scss", ".less"):
            for name, value in re.findall(r"(--[\w-]+)\s*:\s*([^;}{]+);", text):
                tokens.append([name, value.strip()[:40], f])
            if ext == ".scss":
                for name, value in re.findall(r"^\s*(\$[\w-]+)\s*:\s*([^;]+);", text, re.M):
                    tokens.append([name, value.strip()[:40], f])
        elif ext == ".xml" and re.search(r"res/values[\w-]*/(colors|dimens|styles|themes)\.xml$", f):
            for kind, name, value in re.findall(r"<(color|dimen)\s+name=\"([\w.]+)\"\s*>([^<]+)<", text):
                tokens.append([f"@{kind}/{name}", value.strip(), f])
        elif ext == ".dart":
            for name, value in re.findall(r"(?:static\s+)?const\s+(?:Color\s+)?(\w+)\s*=\s*(Color\(0x[0-9A-Fa-f]{8}\))", text):
                tokens.append([name, value, f])
            for name, value in re.findall(r"(?:static\s+)?const\s+(?:double\s+)?(\w*(?:[Ss]pacing|[Pp]adding|[Rr]adius|[Gg]ap)\w*)\s*=\s*([\d.]+)", text):
                tokens.append([name, value, f])
            for m in re.findall(r"seedColor:\s*([^,)\n]+)", text):
                tokens.append(["ColorScheme.seedColor", m.strip()[:40], f])
        elif ext == ".kt":
            for name, value in re.findall(r"val\s+(\w+)\s*=\s*(Color\(0x[0-9A-Fa-f]{8}\))", text):
                tokens.append([name, value, f])
        elif re.search(r"tailwind\.config\.[cm]?[jt]s$", f):
            block = re.search(r"(?:extend\s*:\s*\{|theme\s*:\s*\{)(.*)", text, re.S)
            for name, value in re.findall(r"['\"]?([\w-]+)['\"]?\s*:\s*['\"](#[0-9A-Fa-f]{3,8}|rgb[^'\"]+|\d+(?:px|rem|em))['\"]",
                                          block.group(1) if block else ""):
                tokens.append([f"tailwind.{name}", value, f])
        elif ext == ".json" and re.search(r"(^|/)(tokens?|design-tokens)[\w.-]*\.json$", f):
            def walk(node, prefix=""):
                if isinstance(node, dict):
                    if "value" in node and not isinstance(node["value"], (dict, list)):
                        tokens.append([prefix.strip("."), str(node["value"])[:40], f])
                        return
                    for k, v in node.items():
                        walk(v, f"{prefix}.{k}")
            try:
                walk(json.loads(text))
            except json.JSONDecodeError:
                pass
    if not tokens:
        return "No design tokens detected in code."
    def category(name, value):
        n, v = name.lower(), value.lower()
        if re.search(r"color|colour|bg|background|primary|secondary|accent|surface|text|border", n) or \
                re.match(r"#[0-9a-f]{3,8}$|rgb|hsl|color\(0x", v):
            return "Color"
        if re.search(r"font|text|type|line-height|letter", n):
            return "Typography"
        if re.search(r"radius|round", n):
            return "Radius"
        if re.search(r"space|spacing|gap|padding|margin|size|dimen", n) or re.match(r"[\d.]+(px|rem|em|dp|sp)?$", v):
            return "Spacing/size"
        return "Other"
    seen, rows = set(), []
    for name, value, f in tokens:
        if (name, f) not in seen:
            seen.add((name, f))
            rows.append([category(name, value), name, value, f])
    rows.sort()
    return f"### Detected tokens ({len(rows)})\n" + md_table(["Category", "Token", "Value", "Defined in"], rows, 250)


def auto_state(repo: Path, files: list[str]) -> str:
    routes, enums, stores = [], [], []
    for f in files:
        ext = Path(f).suffix
        m = re.match(r"(?:.*/)?(?:src/)?app/(.+)/page\.(?:tsx|jsx|ts|js|mdx)$|(?:.*/)?(?:src/)?app/page\.(?:tsx|jsx|ts|js)$", f)
        if m:
            routes.append(["/" + (m.group(1) or "").replace("\\", "/"), "Next.js app router", f])
            continue
        m = re.match(r"(?:.*/)?(?:src/)?pages/(?!api/|_)(.+)\.(?:tsx|jsx|ts|js|vue)$", f)
        if m:
            routes.append(["/" + re.sub(r"(^|/)index$", "", m.group(1)), "file-based pages", f])
            continue
        if ext not in (".ts", ".tsx", ".js", ".jsx", ".vue", ".svelte", ".dart", ".kt", ".java", ".swift", ".py", ".go",
                       ".rs", ".cs", ".xml"):
            continue
        text = read(repo, f)
        if not text:
            continue
        if ext in (".ts", ".tsx", ".js", ".jsx", ".vue"):
            for p in re.findall(r"<Route\b[^>]*\bpath\s*=\s*[{]?['\"]([^'\"]+)", text):
                routes.append([p, "React Router", f])
            for p in re.findall(r"\bpath\s*:\s*['\"](/[^'\"]*)['\"]", text):
                routes.append([p, "router config", f])
            for name in re.findall(r"createSlice\(\s*\{\s*name\s*:\s*['\"](\w+)", text):
                stores.append([name, "Redux slice", f])
            for name in re.findall(r"(?:export\s+)?const\s+(use\w+Store)\s*=\s*(?:create|defineStore)\b", text):
                stores.append([name, "store", f])
        if ext == ".dart":
            for p in re.findall(r"GoRoute\(\s*(?:name:\s*[^,]+,\s*)?path:\s*['\"]([^'\"]+)", text):
                routes.append([p, "go_router", f])
            for p in re.findall(r"['\"](/[\w/-]*)['\"]\s*:\s*\(\s*\w*\s*\)\s*=>", text):
                routes.append([p, "MaterialApp routes", f])
            for name in re.findall(r"class\s+(\w+)\s+extends\s+(?:Bloc|Cubit|ChangeNotifier|StateNotifier|Notifier|AsyncNotifier)\b", text):
                stores.append([name, "state holder", f])
        if ext == ".xml" and f.endswith("AndroidManifest.xml"):
            for a in re.findall(r"<activity[^>]*android:name=\"([\w.]+)\"", text):
                routes.append([a, "Android activity", f])
        if ext == ".xml" and "/navigation/" in f:
            for d in re.findall(r"<(?:fragment|activity|dialog)[^>]*android:id=\"@\+id/(\w+)\"", text):
                routes.append([d, "nav graph destination", f])
        for m in re.finditer(r"\benum\s+(?:class\s+)?(\w*(?:State|Status|Phase|Mode|Stage|Step))\b[^{]*\{([^}]*)\}", text):
            members = [re.split(r"[\s(=:,]", x.strip())[0] for x in m.group(2).split(",")
                       if x.strip() and not x.strip().startswith(("//", "/*", ";"))]
            enums.append([m.group(1), ", ".join(x for x in members if x)[:120], f])
        if ext == ".py":
            for m in re.finditer(r"^class\s+(\w*(?:State|Status|Phase|Mode|Stage|Step))\((?:str,\s*)?(?:enum\.)?(?:Str|Int)?Enum\):\n((?:[ \t]+.*\n)+)",
                                 text, re.M):
                members = re.findall(r"^\s+([A-Z_][A-Z0-9_]*)\s*=", m.group(2), re.M)
                enums.append([m.group(1), ", ".join(members)[:120], f])
    out = []
    dedup = lambda rows: sorted({tuple(r) for r in rows})
    if routes:
        out.append(f"### Screens / routes ({len(dedup(routes))})\n" + md_table(["Route/screen", "Kind", "Defined in"], [list(r) for r in dedup(routes)]))
    if enums:
        out.append(f"### State enums ({len(dedup(enums))})\n" + md_table(["Enum", "States", "Defined in"], [list(r) for r in dedup(enums)]))
    if stores:
        out.append(f"### State holders ({len(dedup(stores))})\n" + md_table(["Name", "Kind", "Defined in"], [list(r) for r in dedup(stores)]))
    return "\n\n".join(out) or "No routes, state enums or stores detected in code."


def auto_plan(text: str) -> str:
    manual = strip_auto(text)
    done = len(re.findall(r"^\s*[-*]\s+\[[xX]\]", manual, re.M))
    todo = len(re.findall(r"^\s*[-*]\s+\[ \]", manual, re.M))
    nxt = re.search(r"^\s*[-*]\s+\[ \]\s+(.+)$", manual, re.M)
    total = done + todo
    pct = f" ({round(100 * done / total)}%)" if total else ""
    return f"{done}/{total} steps done{pct}" + (f". Next: {nxt.group(1).strip()[:120]}" if nxt else "")


AUTO = {"STACK": auto_stack, "SCHEMA": auto_schema, "TOKENS": auto_tokens, "STATE": auto_state}


# ------------------------------------------------------------------ file ops
def strip_auto(text: str) -> str:
    return re.sub(re.escape(AUTO_START) + r".*?" + re.escape(AUTO_END), "", text, flags=re.S)


def with_auto(text: str, content: str) -> str:
    block = f"{AUTO_START}\n<!-- generated by vault.py sync: do not edit by hand -->\n{content.strip()}\n{AUTO_END}"
    if AUTO_START in text and AUTO_END in text:
        return re.sub(re.escape(AUTO_START) + r".*?" + re.escape(AUTO_END), lambda _: block, text, flags=re.S)
    return text.rstrip() + "\n\n" + block + "\n"


def current_auto(text: str) -> str | None:
    m = re.search(re.escape(AUTO_START) + r"\n(?:<!--.*?-->\n)?(.*?)\n" + re.escape(AUTO_END), text, re.S)
    return m.group(1).strip() if m else None


def router_block(vdir_rel: str) -> str:
    rows = [f"| {i:02d} | [{n}]({vdir_rel}/{n}.md) | {ROUTER_ROWS[n][0]} | {ROUTER_ROWS[n][1]} | {ROUTER_ROWS[n][2]} |"
            for i, n in enumerate(ORDER, 1)]
    return "\n".join([ROUTER_START,
                      "## Project vault (mandatory: read before working, update in the same change)",
                      "", "| # | File | Holds | Read when | Update when |", "|---|---|---|---|---|", *rows, "",
                      "- Read only the vault files relevant to the task; PLAN.md at the start of every session.",
                      "- When a change alters what a vault file describes, update that file in the same commit.",
                      "- Detected sections are regenerated with `vault.py sync` (project-vault skill); "
                      "`vault.py check` must pass before committing.",
                      ROUTER_END])


def write_router(repo: Path, vdir: Path) -> bool:
    rel = os.path.relpath(vdir, repo).replace("\\", "/")
    claude = claude_md(repo)
    text = claude.read_text(encoding="utf-8") if claude.exists() else "# CLAUDE.md\n"
    block = router_block(rel)
    if ROUTER_START in text and ROUTER_END in text:
        new = re.sub(re.escape(ROUTER_START) + r".*?" + re.escape(ROUTER_END), lambda _: block, text, flags=re.S)
    else:
        new = text.rstrip() + "\n\n" + block + "\n"
    if new != text:
        claude.write_text(new, encoding="utf-8")
        return True
    return False


def generated(repo: Path, name: str, text: str, files: list[str]) -> str | None:
    if name == "PLAN":
        return auto_plan(text)
    if name in AUTO:
        return AUTO[name](repo, files)
    return None


def sync(repo: Path, vdir: Path, create: bool) -> list[str]:
    files = git_files(repo)
    changed = []
    vdir.mkdir(parents=True, exist_ok=True)
    for name in ORDER:
        path = vdir / f"{name}.md"
        if not path.exists():
            if not create:
                continue
            path.write_text(TEMPLATES[name], encoding="utf-8")
            changed.append(f"created {path.relative_to(repo)}")
        text = path.read_text(encoding="utf-8")
        gen = generated(repo, name, text, files)
        if gen is not None:
            new = with_auto(text, gen)
            if new != text:
                path.write_text(new, encoding="utf-8")
                changed.append(f"updated {path.relative_to(repo)} (detected section)")
    if write_router(repo, vdir):
        changed.append("updated CLAUDE.md router")
    return changed


def check(repo: Path, vdir: Path) -> list[dict]:
    findings = []
    add = lambda sev, where, problem, fix: findings.append({"severity": sev, "where": where, "problem": problem, "fix": fix})
    rel = os.path.relpath(vdir, repo).replace("\\", "/")
    files = None
    for name in ORDER:
        path = vdir / f"{name}.md"
        where = f"{rel}/{name}.md"
        if not path.exists():
            add("high", where, f"{name}.md missing", "run `vault.py init` and fill it")
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        manual = strip_auto(text)
        na = re.search(r"^Status:\s*N/?A\b\s*[-:]?\s*(.*)$", manual, re.M | re.I)
        if na and not na.group(1).strip():
            add("low", where, "marked N/A without a reason", "write `Status: N/A - <reason>`")
        todos = manual.count(TODO)
        if todos and not na:
            sev = "medium" if name in ("PRD", "PLAN") else "low"
            add(sev, where, f"{todos} unfilled {TODO} placeholder(s)",
                "fill it in with the user/agent knowledge (or mark `Status: N/A - <reason>` where it truly does not apply)")
        if name == "PLAN" and not re.search(r"^\s*[-*]\s+\[[ xX]\]\s+\S", manual, re.M):
            add("medium", where, "no plan steps", "write ordered `- [ ] step` items")
        if name in AUTO:  # PLAN progress is derived on the fly; ticking a step never blocks a commit
            files = files if files is not None else git_files(repo)
            want = generated(repo, name, text, files)
            if current_auto(text) != (want or "").strip():
                add("medium", where, "detected section out of date with the code", "run `vault.py sync` and commit")
    claude = read(repo, str(claude_md(repo).relative_to(repo)))
    if ROUTER_START not in claude:
        add("high", "CLAUDE.md", "no vault router in CLAUDE.md", "run `vault.py sync`")
    elif re.search(re.escape(ROUTER_START) + r".*?" + re.escape(ROUTER_END), claude, re.S).group(0) != router_block(rel):
        add("medium", "CLAUDE.md", "vault router out of date", "run `vault.py sync`")
    return findings


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("cmd", choices=["init", "sync", "check", "status"])
    ap.add_argument("repo", nargs="?", default=".")
    ap.add_argument("--dir", help="vault folder relative to the repo (default: existing one, else docs/vault)")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--gate", action="store_true", help="check: only fail on missing files, router or stale sections")
    args = ap.parse_args()
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=args.repo, capture_output=True, text=True,
                         encoding="utf-8", errors="replace")
    repo = Path(out.stdout.strip() if out.returncode == 0 else args.repo).resolve()
    vdir = find_dir(repo, args.dir)

    if args.cmd in ("init", "sync"):
        changes = sync(repo, vdir, create=args.cmd == "init")
        print("\n".join(changes) if changes else "vault already up to date")
        if args.cmd == "init":
            print(f"\nNext: fill {os.path.relpath(vdir, repo)}/PRD.md and PLAN.md (and the manual parts of the others), "
                  "then commit the vault with CLAUDE.md.")
        return 0
    findings = check(repo, vdir)
    if args.cmd == "status":
        present = sum((vdir / f"{n}.md").exists() for n in ORDER)
        stale = [f["where"].split("/")[-1][:-3] for f in findings if "out of date" in f["problem"] and f["where"] != "CLAUDE.md"]
        todo = [f["where"].split("/")[-1][:-3] for f in findings if "placeholder" in f["problem"]]
        plan = vdir / "PLAN.md"
        prog = auto_plan(plan.read_text(encoding="utf-8")) if plan.exists() else ""
        if present == 0:
            print("[precision-kit vault] MISSING: this project has no vault (PRD, STATE, TOKENS, STACK, SCHEMA, PLAN). "
                  "Create it now with the project-vault skill (`vault.py init`), then fill PRD and PLAN with the user.")
        else:
            print(f"[precision-kit vault] {present}/6 files; PLAN {prog or 'no steps'}"
                  + (f"; stale: {', '.join(stale)} (run vault.py sync)" if stale else "")
                  + (f"; unfilled: {', '.join(todo)}" if todo else "")
                  + ". Read PLAN.md first, then only the vault files the task needs (see CLAUDE.md router).")
        return 0
    if args.gate:
        findings = [f for f in findings if f["severity"] == "high" or "out of date" in f["problem"]]
    if args.json:
        print(json.dumps({"vault": os.path.relpath(vdir, repo), "findings": findings}, indent=2, ensure_ascii=False))
    else:
        print(f"Vault {os.path.relpath(vdir, repo)}: {len(findings)} finding(s)")
        for f in findings:
            print(f"  [{f['severity']}] {f['where']}: {f['problem']} -> {f['fix']}")
        if not findings:
            print("  all six files present, filled, in sync and routed from CLAUDE.md")
    return 1 if any(f["severity"] in ("high", "medium") for f in findings) else 0


if __name__ == "__main__":
    for _stream in (sys.stdout, sys.stderr):  # UTF-8 output even on legacy Windows consoles
        if hasattr(_stream, "reconfigure"):
            _stream.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
